-- ปิดยอดแล้วรับเงินไม่ได้จนกว่าจะ "เปิดรอบขายใหม่" (2026-10-08 เจ้าของสั่ง)
-- salesResumedAt = เวลาที่แคชเชียร์กดเปิดรอบขายใหม่หลังปิดรอบนี้ · null = ยังไม่เปิด = ล็อกการรับเงินของคนนั้น (เฉพาะวันนี้)
ALTER TABLE "cashier_closing" ADD COLUMN "salesResumedAt" TIMESTAMP(3);

-- รอบที่ปิดไว้ก่อนมีกติกานี้: เดิมขายต่อได้ทันทีหลังปิด → ถือว่าเปิดรอบขายใหม่แล้ว ณ เวลาที่ปิด
-- ไม่งั้นแคชเชียร์ที่ปิดรอบไว้ช่วงเช้าวัน deploy จะรับเงินไม่ได้ทันทีโดยไม่รู้ตัว
